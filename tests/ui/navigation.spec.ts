import { test, expect } from '@playwright/test';

test('URLs restore runs, steps, files, filters and views across refresh, bookmarks and history', async ({ page, request, context }) => {
  const title = `URL navigation ${Date.now()}`;
  const response = await request.post('/api/runs', { data: { title, task: 'Verify navigation only.', project: 'welcome', workflowId: 'quick-review', mode: 'demo' } });
  expect(response.status()).toBe(201);
  const run = await response.json();
  await page.goto(`/?q=${encodeURIComponent(title)}&mode=demo&scope=history`);
  await expect(page.locator('.run-card')).toHaveCount(1);
  await page.locator('.run-card').click();
  await expect(page).toHaveURL(new RegExp(`run=${run.id}`));
  await page.locator('.step-list button').first().click();
  await page.getByRole('tab', { name: 'Files', exact: true }).click();
  await page.getByRole('button', { name: 'README.md', exact: true }).click();
  await expect(page.locator('.file-viewer')).toContainText('Welcome');
  const bookmark = page.url();
  expect(new URL(bookmark).searchParams.get('file')).toBe('README.md');
  expect(new URL(bookmark).searchParams.get('step')).toBe(run.steps[0].definition.id);
  await page.reload();
  await expect(page.locator('.detail-title')).toHaveText(title);
  await expect(page.getByRole('tab', { name: 'Files', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('.step-list button').first()).toHaveAttribute('aria-current', 'step');
  await expect(page.locator('.file-viewer')).toContainText('Welcome');
  const other = await context.newPage();
  await other.goto(bookmark);
  await expect(other.locator('.detail-title')).toHaveText(title);
  await expect(other.locator('.file-viewer')).toContainText('Welcome');
  await other.close();
  await page.getByRole('tab', { name: 'Activity', exact: true }).click();
  await page.getByRole('button', { name: 'All events', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('tab', { name: 'Activity', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Agents', exact: true }).click();
  await expect(page).toHaveURL(/view=agents/);
  await page.goBack();
  await expect(page.locator('.detail-title')).toHaveText(title);
  await expect(page.getByRole('tab', { name: 'Activity', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.goForward();
  await expect(page.getByRole('heading', { name: 'Agents', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Agents', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Runs', exact: true }).click();
  await expect(page.getByRole('searchbox', { name: 'Search runs' })).toHaveValue(title);
  await expect(page.getByLabel('Filter by mode')).toHaveValue('demo');
  await expect(page.locator('.run-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Workflows', exact: true }).click();
  await page.locator('.wf-list').getByRole('button').filter({ hasText: 'Fix and Verify' }).click();
  await expect(page).toHaveURL(/workflow=fix-verify/);
  await page.reload();
  await expect(page.getByLabel('Workflow name', { exact: true })).toHaveValue('Fix and Verify');
  await page.goto('/?run=missing-run&tab=invalid&view=invalid');
  await expect(page.getByRole('heading', { name: 'Run not found' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to runs', exact: true }).click();
  expect(new URL(page.url()).searchParams.has('run')).toBe(false);
  await expect(page.getByRole('heading', { name: 'Runs', exact: true })).toBeVisible();
});

